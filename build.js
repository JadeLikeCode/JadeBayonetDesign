#!/usr/bin/env node
/*
  Creates one folder per project so links like jadebayonet.com/nothing-ice-cream work
  on GitHub Pages (which only serves real files).

  Each /slug/index.html is a copy of index.html with that project's title and
  description filled in, so link previews (iMessage, LinkedIn, Slack) show the project.
  The page itself opens the right drawer automatically.

  Run after adding a project or changing a slug/title/blurb:
    node build.js
*/
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = __dirname;
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "js/projects.js"), "utf8"), sandbox);
const projects = sandbox.window.PROJECTS || [];

const template = fs.readFileSync(path.join(root, "index.html"), "utf8");
const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const isPlaceholder = (s = "") => /^\[.*\]$/.test(String(s).trim());

// Remove folders from projects that no longer exist (only ones this script made).
for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const marker = path.join(root, entry.name, ".generated");
  if (fs.existsSync(marker) && !projects.some((p) => p.slug === entry.name)) {
    fs.rmSync(path.join(root, entry.name), { recursive: true });
    console.log(`removed  /${entry.name}/`);
  }
}

for (const p of projects) {
  const title = `${p.title} — Jade Bayonet`;
  const desc = [p.blurb, p.overview].find((s) => s && !isPlaceholder(s)) || `${p.title}, a project by Jade Bayonet.`;

  const html = template
    .replace(/<title>[^<]*<\/title>/, `<title>${attr(title)}</title>`)
    .replace(/(<meta name="description" content=")[^"]*(")/, `$1${attr(desc)}$2`)
    .replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${attr(title)}$2`)
    .replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${attr(desc)}$2`)
    .replace(/(href|src)="(assets|css|js)\//g, '$1="../$2/')
    .replace('href="index.html"', 'href="../"')
    .replace('var SITE_BASE = "";', 'var SITE_BASE = "../";')
    .replace("<!doctype html>", `<!doctype html>\n<!-- Generated by build.js from index.html. Edit index.html, then run: node build.js -->`);

  const dir = path.join(root, p.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), html);
  fs.writeFileSync(path.join(dir, ".generated"), "");
  console.log(`built    /${p.slug}/`);
}

// Unknown URLs fall back to the homepage instead of GitHub's 404 page.
// (404 pages can be served at any depth, so it resolves files from the site root.)
fs.writeFileSync(path.join(root, "404.html"), template.replace("<head>", '<head>\n  <base href="/" />'));
console.log("built    /404.html");
